-- Simplified core-banking schema used by the DB validation tests.
-- Business rules are enforced by constraints, the way a real banking backend would.
DROP TABLE IF EXISTS transactions;
DROP TABLE IF EXISTS accounts;

CREATE TABLE accounts (
    account_id   NUMBER(10)     PRIMARY KEY,
    customer_id  NUMBER(10)     NOT NULL,
    account_type VARCHAR2(10)   NOT NULL CHECK (account_type IN ('CHECKING', 'SAVINGS')),
    balance      NUMBER(15, 2)  NOT NULL CHECK (balance >= 0)
);

CREATE TABLE transactions (
    txn_id       NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_acct    NUMBER(10)     NOT NULL REFERENCES accounts (account_id),
    to_acct      NUMBER(10)     NOT NULL REFERENCES accounts (account_id),
    amount       NUMBER(15, 2)  NOT NULL CHECK (amount > 0),
    description  VARCHAR2(255),
    created_at   TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL
);

